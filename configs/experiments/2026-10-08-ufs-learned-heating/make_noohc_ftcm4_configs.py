# ruff: noqa: E501
"""UFS fine-tunes of the NO-corrector CM4 ppad pretrains (Troy 2026-10-23: retrain CM4 without the OHC corrector, then FT on UFS).
Config = the ufsvars UFS fine-tune's data/validation/inference/optimizer/epochs (cm4vars-uh store, UFS stats incl. the CM4
placeholder entries, 60 epochs, lr 5e-5, MSE, 4 steps, parameter_init /ckpt.tar) + the pretrain's own stepper block
(CM4 variable set incl. placeholders, lat_pad, diagnostic SSH, fill value, residual names; NO ocean_heat_content_correction,
no learned heating), with corrector_disabled_epochs 0 and the UFS zos reference 0.0.
"""

import pathlib

import yaml

HERE = pathlib.Path(__file__).resolve().parent
PP = pathlib.Path(
    "/home/troya/ace-ppad-zs240/configs/experiments/2026-10-09-4deg-hybrid-ppad"
)
base = yaml.safe_load(open(HERE / "resid-ohc-cap0005-learnedheat-ftcm4-ufsvars.yaml"))
for arm, pre in [
    ("ff-noohc-ftcm4", "ff-noohc-ppad"),
    ("resid-noohc-fmean-ftcm4", "resid-noohc-ppad-fmean"),
]:
    p = yaml.safe_load(open(PP / f"{pre}.yaml"))
    c = {k: v for k, v in base.items() if k != "stepper"}
    st = p["stepper"]
    cc = st["step"]["config"]
    assert (
        "ocean_heat_content_correction" not in cc["corrector"]["config"]
        and "unaccounted_heating" not in cc["out_names"]
    )
    cc["corrector"]["config"]["corrector_disabled_epochs"] = 0
    cc["corrector"]["config"]["zos_global_mean_correction"] = {
        "reference_global_mean": 0.0
    }
    cc["normalization"] = base["stepper"]["step"]["config"]["normalization"]
    st.pop("parameter_init", None)
    c["stepper"] = st
    hdr = (
        f"# {arm}: UFS 4deg fine-tune (cm4vars-uh store, UFS stats + placeholder entries, 60 ep, lr 5e-5) of the NO-corrector CM4 ppad\n"
        f"# pretraining {pre} (samudra-ppad4deg-{pre}); stepper = that pretraining's (no ocean_heat_content_correction, no\n"
        f"# learned heating), corrector_disabled_epochs 0, zos reference 0.0. Generated by make_noohc_ftcm4_configs.py. Troy 2026-10-24.\n"
    )
    (HERE / f"{arm}.yaml").write_text(
        hdr + yaml.safe_dump(c, sort_keys=False, width=120)
    )
    print(
        "wrote",
        arm,
        "| out",
        len(cc["out_names"]),
        "in",
        len(cc["in_names"]),
        "| fill",
        st.get("input_masking", {}).get("fill_value"),
        "| residual",
        len(cc.get("residual_prediction", {}).get("names", []))
        if cc.get("residual_prediction")
        else 0,
    )
