#!/usr/bin/env python
# ruff: noqa: E501
# mypy: ignore-errors
"""Apples-to-apples test of CM4 pretraining for the SamudrACE-UFS paper (Troy 2026-10-26), all at 4deg.

Two oceans with ONE recipe (the paper-1 hybrid: James's ppad Samudra, mean fill, thetao_0..18 as normalized residuals, the
uncapped scaled-temperature heat-content corrector, prescribed_open_ocean surface flux, sst an OUTPUT-ONLY diagnostic channel):
  scratch : UFS 4deg replay from random initialization, 200 epochs, lr 1e-4 (the program's from-scratch protocol)
  ftcm4   : CM4 4deg pretrain (75 epochs, CM4 stats) then the UFS fine-tune, 60 epochs, lr 5e-5 (the program's FT protocol)
then the SAME alternating coupled fine-tune of each with the ERA5 4deg daily ACE2S (12 epochs, EnsembleLoss, one component per
batch), then the same evaluations: 30-yr coupled rollout from 1994 and 120 coupled hindcasts over the untouched 2002-2011 decade.

Stepper = ../2026-10-09-4deg-hybrid-ppad/resid-ohc-cap0005-ppad-fmean.yaml minus the corrector cap, minus sst in in_names.
Writes: cm4-pretrain.yaml, ufs-scratch.yaml, ufs-ftcm4.yaml, coupled/{scratch,ftcm4}-era5-coupledft-spb.yaml.
"""

import copy
import pathlib
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
EXP = HERE.parent
BASE = EXP / "2026-10-09-4deg-hybrid-ppad" / "resid-ohc-cap0005-ppad-fmean.yaml"
UFS_FT = (
    EXP / "2026-10-08-ufs-learned-heating" / "resid-noohc-fmean-ftcm4.yaml"
)  # UFS data/validation/inference/optimizer template
COUPLED = EXP / "2026-10-14-ufs4deg-era5-coupling"
UFS_ZOS_REF = 0.0  # the UFS fine-tunes' zos reference (see make_noohc_ftcm4_configs.py)


def recipe_stepper(base_stepper: dict) -> dict:
    st = copy.deepcopy(base_stepper)
    cc = st["step"]["config"]
    ohc = cc["corrector"]["config"]["ocean_heat_content_correction"]
    ohc.pop(
        "max_scaled_contraction", None
    )  # James's uncapped corrector (the 1deg paper-1 run)
    assert ohc == {"method": "scaled_temperature"}, ohc
    cc["in_names"] = [
        n for n in cc["in_names"] if n != "sst"
    ]  # sst: output-only diagnostic, the ACE way
    assert "sst" in cc["out_names"] and "sst" not in cc["in_names"]
    assert cc["residual_prediction"]["names"] == [f"thetao_{i}" for i in range(19)]
    assert st["input_masking"]["fill_value"] == "mean"
    return st


def main() -> None:
    base = yaml.safe_load(BASE.read_text())
    ufs = yaml.safe_load(UFS_FT.read_text())
    stepper = recipe_stepper(base["stepper"])

    # 1. CM4 4deg pretrain: the base config with the recipe stepper (75 ep, lr 1e-4, corrector_disabled_epochs 1, CM4 stats)
    cm4 = copy.deepcopy(base)
    cm4["stepper"] = copy.deepcopy(stepper)
    assert cm4["max_epochs"] == 75 and cm4["optimization"]["lr"] == 1e-4
    assert (
        cm4["stepper"]["step"]["config"]["corrector"]["config"][
            "corrector_disabled_epochs"
        ]
        == 1
    )
    (HERE / "cm4-pretrain.yaml").write_text(
        "# cm4-pretrain: CM4 4deg ppad pretrain of the paper-1 hybrid recipe (thetao residual, uncapped OHC corrector, sst output-only,\n"
        "# mean fill; = ../2026-10-09-4deg-hybrid-ppad/resid-ohc-cap0005-ppad-fmean.yaml minus the cap and minus sst as an input), the\n"
        "# 4deg twin of the 1deg run resid-ohc-ppad-sstdiag-fmean-1deg and the pretrain of the 'ftcm4' arm. Generated by make_configs.py.\n"
        + yaml.safe_dump(cm4, sort_keys=False, width=120)
    )

    # 2. UFS stages: the UFS fine-tune template's data/validation/inference/logging + the recipe stepper (UFS stats, zos ref 0)
    def ufs_cfg(epochs: int, lr: float, from_ckpt: bool, disabled_epochs: int) -> dict:
        c = {k: copy.deepcopy(v) for k, v in ufs.items() if k != "stepper"}
        c["max_epochs"] = epochs
        c["optimization"]["lr"] = lr
        c["stepper_training"] = {"n_forward_steps": 4, "loss": {"type": "MSE"}}
        if from_ckpt:
            c["stepper_training"]["parameter_init"] = {"weights_path": "/ckpt.tar"}
            c["evaluate_before_training"] = True
        else:
            c.pop("evaluate_before_training", None)
        st = copy.deepcopy(stepper)
        cc = st["step"]["config"]
        cc["corrector"]["config"]["corrector_disabled_epochs"] = disabled_epochs
        cc["corrector"]["config"]["zos_global_mean_correction"] = {
            "reference_global_mean": UFS_ZOS_REF
        }
        assert (
            cc["normalization"] == ufs["stepper"]["step"]["config"]["normalization"]
        )  # /ocean_stats paths, full-field + residual
        c["stepper"] = st
        return c

    scratch = ufs_cfg(200, 1e-4, from_ckpt=False, disabled_epochs=1)
    (HERE / "ufs-scratch.yaml").write_text(
        "# ufs-scratch: the recipe trained FROM SCRATCH on the UFS 4deg replay (cm4vars-uh store, UFS stats), 200 epochs, lr 1e-4,\n"
        "# corrector off for epoch 1 (as the CM4 pretrain); train 1994-2001 + 2012-2021, 2002-2011 untouched, val 2022-2023. Generated by make_configs.py.\n"
        + yaml.safe_dump(scratch, sort_keys=False, width=120)
    )
    ft = ufs_cfg(60, 5e-5, from_ckpt=True, disabled_epochs=0)
    (HERE / "ufs-ftcm4.yaml").write_text(
        "# ufs-ftcm4: the recipe FINE-TUNED on the UFS 4deg replay from the CM4 4deg pretrain cm4-pretrain.yaml (best_inference_ckpt at\n"
        "# /ckpt.tar), 60 epochs, lr 5e-5, UFS stats; same data windows as ufs-scratch. Generated by make_configs.py.\n"
        + yaml.safe_dump(ft, sort_keys=False, width=120)
    )

    # 3. Coupled stage: make_coupled_ft_config.py --joint on each UFS ocean config, then alternating updates (spb)
    sys.path.insert(0, str(COUPLED))
    import make_coupled_ft_config as mk  # noqa: E402

    for arm in ("scratch", "ftcm4"):
        ocean_cfg = yaml.safe_load((HERE / f"ufs-{arm}.yaml").read_text())
        # reuse the generator by pointing it at a temporary copy under its expected directory
        tmp = EXP / "2026-10-08-ufs-learned-heating" / f"_pvs-{arm}.yaml"
        tmp.write_text(yaml.safe_dump(ocean_cfg, sort_keys=False))
        try:
            mk.main(f"_pvs-{arm}", f"_pvs-{arm}-coupledft", joint=True)
        finally:
            tmp.unlink()
        out = COUPLED / f"_pvs-{arm}-coupledft.yaml"
        cfg = yaml.safe_load(out.read_text())
        out.unlink()
        cfg["stepper_training"]["optimize_single_component_per_batch"] = (
            True  # alternating updates (the four-stage report recipe)
        )
        cfg["stepper"]["ocean"]["stepper"]["step"]["config"]["corrector"]["config"][
            "corrector_disabled_epochs"
        ] = 0  # fine-tune: corrector on from epoch 1 in BOTH arms
        assert (
            cfg["max_epochs"] == 12
            and cfg["stepper_training"]["atmosphere"]["loss_weight"] == 1.0
        )
        (HERE / "coupled" / f"{arm}-era5-coupledft-spb.yaml").write_text(
            f"# {arm}-era5-coupledft-spb: ALTERNATING coupled FT (both trained, one component per batch, EnsembleLoss, 12 epochs) of the\n"
            f"# UFS 4deg ocean ufs-{arm}.yaml (best_inference_ckpt at /ocean_ckpt.tar) with the ERA5 4deg daily ACE2S (/atmos_ckpt.tar):\n"
            f"# the coupled stage of the pretrain-vs-scratch test, identical for both arms. Generated by make_configs.py via\n"
            f"# ../2026-10-14-ufs4deg-era5-coupling/make_coupled_ft_config.py --joint.\n"
            + yaml.safe_dump(cfg, sort_keys=False, width=120)
        )
    for f in sorted(HERE.glob("*.yaml")) + sorted((HERE / "coupled").glob("*.yaml")):
        print("wrote", f.relative_to(EXP))


if __name__ == "__main__":
    main()
