MONTHLY_ATMOS_NAMES = [
    "air_temperature_0",
    "air_temperature_7",
    "LHTFLsfc",
    "SHTFLsfc",
    "DSWRFsfc",
    "USWRFsfc",
    "DLWRFsfc",
    "ULWRFsfc",
    "ULWRFtoa",
    "USWRFtoa",
    "surface_temperature",
    "total_frozen_precipitation_rate",
    "PRATEsfc",
    "net_energy_flux_toa_into_atmosphere",  # derived
]
MONTHLY_OCEAN_NAMES = [
    "hfds_total_area",
    "thetao_0",
    "thetao_18",
    "ocean_sea_ice_fraction",
    "ocean_heat_content",  # derived
    "ocean_heat_content_tendency",  # derived
]

MONTHLY_EXPERIMENT_DIR = (
    "gs://vcm-ml-experiments/spencerc/"
    "2026-11-06-hybrid1deg-cft-rs1-replay-abrupt4xCO2-ic1-100yr-monthly"
)

MONTHLY_COMMENT = """
# Writes monthly means of a subset of the atmosphere and ocean predictions to
# <experiment_dir>/{atmosphere,ocean}/monthly_mean_predictions.zarr. The results
# go straight to GCS, so the zarr writer is used: the netCDF monthly writer
# (save_monthly_files) and log_to_file only support local paths, and the log file
# is skipped with a warning."""


def _monthly_files_yaml(names: list[str]) -> str:
    return (
        "\n    files:"
        "\n      - label: monthly_mean_predictions"
        "\n        save_reference: false"
        "\n        time_coarsen:"
        "\n          method: monthly_mean"
        "\n        format:"
        "\n          name: zarr"
        "\n        names:" + "".join(f"\n          - {n}" for n in names)
    )


EXTENSION_COMMENT = """
# Initial conditions and forcing are as in inference-config-cm4-abrupt4xCO2-ic1.yaml,
# except that both forcing datasets are repeated in time to cover 0301-{end_year:04d}:
# - the piControl atmosphere stores end in 0350, so they are repeated once; the
#   remaining atmosphere forcings are periodic in the noleap calendar and CO2 is
#   {co2_repeat}, so the repeat introduces no discontinuity.
# - the ocean's time-constant forcings file only spans the 150-day window on a
#   5-day axis, so it is tiled well past the {n_times} times needed."""


ABRUPT = dict(
    scenario="abrupt-4xCO2",
    co2_clause=f"with CO2 held at 4x ({CO2_4X} ppm)",
    co2_overwrite=(
        "\n          overwrite:"
        "\n            constant:"
        f"\n              carbon_dioxide: {CO2_4X}"
    ),
)
PICONTROL = dict(
    scenario="piControl",
    co2_clause="with CO2 from the piControl forcing",
    co2_overwrite="",
)

PICONTROL_COMMENT = """
# Control for the abrupt-4xCO2 100-year runs: the same initial condition and
# forcing, except that CO2 is not overwritten. experiment_dir is set per run with
# an override in experiments.txt."""


CMIP6_LIKE_IC_RUN_COMMENT = """
# Both forcing datasets are repeated in time to cover 0251-{end_year:04d}:
# - the piControl atmosphere stores end in 0350, so they are repeated once; the
#   remaining atmosphere forcings are periodic in the noleap calendar and CO2 is
#   overwritten with a constant, so the repeat introduces no discontinuity.
# - the ocean's time-constant forcings file only spans 150 days on a 5-day
#   axis, so it is tiled well past the {n_times} times needed.
# experiment_dir is set per run with an override in experiments.txt."""

PICONTROL_IC = dict(
    origin="piControl",
    ic_comment=PICONTROL_IC_COMMENT,
    ocean_ic=PICONTROL_OCEAN_IC,
    atmos_ic=PICONTROL_ATMOS_IC,
)


def _n_years(years: int, in_memory: int = 4) -> dict:
    """Template fields for a run of whole noleap years of 5-day ocean steps.

    The repeats cover up to 150 years: the 30-record ocean forcing file tiled
    500 times gives 15000 times, and the 200-year piControl atmosphere stores
    repeated twice cover 400 years from 0151.
    """
    n_steps = 365 * years // 5
    assert (365 * years) % 5 == 0 and years <= 150, years
    # inference requires n_coupled_steps divisible by coupled_steps_in_memory
    assert n_steps % in_memory == 0, (years, in_memory)
    return dict(
        n_coupled_steps=n_steps,
        duration=f"{years}-year",
        steps_comment=f"{years} years of 5-day ocean steps",
        in_memory=in_memory,
        ocean_repeats="\n      n_repeats: 500",
        atmos_repeats="\n          n_repeats: 2",
    )


HUNDRED_YEAR = _n_years(100)
# The CMIP6-like IC runs and the 150-year piControl run also write
# monthly-mean 2m air temperature; the earlier monthly runs, already run, keep
# MONTHLY_ATMOS_NAMES as it was.
MONTHLY_ATMOS_NAMES_WITH_TMP2M = MONTHLY_ATMOS_NAMES + ["TMP2m"]

PICONTROL_150YR_COMMENT = """
# 150-year version of inference-config-cm4-piControl-ic1-100yr-monthly.yaml
# (same initial condition, forcing and CO2) that also writes monthly-mean
# TMP2m; experiment_dir is set per run with an override in experiments.txt."""

# Lengths of the CMIP6-like IC runs in years, with coupled_steps_in_memory:
# 10950 steps (150 years) is not divisible by 4, so that run uses 6, as the
# 90-day ensemble members do.
CMIP6_LIKE_IC_YEARS = {100: 4, 150: 6}


def _extension_comment(scenario: dict, years: int = 100) -> str:
    abrupt = scenario is ABRUPT
    return EXTENSION_COMMENT.format(
        end_year=301 + years,
        n_times=365 * years // 5 + 1,  # n_coupled_steps + the initial condition
        co2_repeat=(
            "overwritten with a constant" if abrupt else "constant in piControl"
        ),
    )


def start_times() -> list[cftime.datetime]:
    """Initial times of ensemble members 1-36, in member order."""
    return [
        cftime.datetime(year, month, 1, calendar="noleap")
        for year in YEARS
        for month in range(1, 13)
    ]


def format_time(time: cftime.datetime) -> str:
    return f"{time.year:04d}-{time.month:02d}-{time.day:02d}T00:00:00"


def main():
    times = start_times()
    for member, time in enumerate(times, start=1):
        text = TEMPLATE.format(
            **ABRUPT,
            description=f"ensemble member {member} of {len(times)}",
            time=format_time(time),
            extra_comment="",
            n_coupled_steps=18,
            duration="90-day",
            steps_comment="90 days of 5-day ocean steps",
            in_memory=6,
            static_forcing=STATIC_FORCING,
            forcing_file=f"ic_{member:04d}.nc",
            **PICONTROL_IC,
            ocean_repeats="",
            atmos_repeats="",
            experiment_dir="/results",
            ocean_files="",
            atmos_files="",
        )
        (HERE / f"inference-config-cm4-abrupt4xCO2-ic{member}.yaml").write_text(text)
    runs = [
        ("cm4-abrupt4xCO2-ic1-100yr", ABRUPT, False, "/results"),
        ("cm4-abrupt4xCO2-ic1-100yr-monthly", ABRUPT, True, MONTHLY_EXPERIMENT_DIR),
        ("cm4-piControl-ic1-100yr-monthly", PICONTROL, True, "/results"),
    ]
    for tag, scenario, monthly, experiment_dir in runs:
        extra_comment = _extension_comment(scenario)
        if scenario is PICONTROL:
            extra_comment += PICONTROL_COMMENT
        if monthly:
            extra_comment += MONTHLY_COMMENT
        text = TEMPLATE.format(
            **scenario,
            description=(
                f"extension of ensemble member 1 of {len(times)}"
                if scenario is ABRUPT
                else "control for abrupt-4xCO2 member 1"
            ),
            time=format_time(times[0]),
            extra_comment=extra_comment,
            static_forcing=STATIC_FORCING,
            forcing_file="ic_0001.nc",
            **PICONTROL_IC,
            **HUNDRED_YEAR,
            experiment_dir=experiment_dir,
            ocean_files=_monthly_files_yaml(MONTHLY_OCEAN_NAMES) if monthly else "",
            atmos_files=_monthly_files_yaml(MONTHLY_ATMOS_NAMES) if monthly else "",
        )
        (HERE / f"inference-config-{tag}.yaml").write_text(text)
    text = TEMPLATE.format(
        **PICONTROL,
        description="control for abrupt-4xCO2 member 1",
        time=format_time(times[0]),
        extra_comment=(
            _extension_comment(PICONTROL, years=150)
            + PICONTROL_150YR_COMMENT
            + MONTHLY_COMMENT
        ),
        static_forcing=STATIC_FORCING,
        forcing_file="ic_0001.nc",
        **PICONTROL_IC,
        **_n_years(150, in_memory=6),
        experiment_dir="/results",
        ocean_files=_monthly_files_yaml(MONTHLY_OCEAN_NAMES),
        atmos_files=_monthly_files_yaml(MONTHLY_ATMOS_NAMES_WITH_TMP2M),
    )
    (HERE / "inference-config-cm4-piControl-ic1-150yr-monthly.yaml").write_text(text)
    t = CMIP6_LIKE_IC_START
    for years, in_memory in CMIP6_LIKE_IC_YEARS.items():
        length = _n_years(years, in_memory)
        run_comment = CMIP6_LIKE_IC_RUN_COMMENT.format(
            end_year=t.year + years, n_times=length["n_coupled_steps"] + 1
        )
        text = TEMPLATE.format(
            **ABRUPT,
            description="run",
            origin="CM4's own CMIP6 abrupt-4xCO2 simulation",
            ic_comment=CMIP6_LIKE_IC_COMMENT,
            ocean_ic=CMIP6_LIKE_IC_OCEAN_IC,
            atmos_ic=CMIP6_LIKE_IC_ATMOS_IC,
            time=format_time(t),
            extra_comment=run_comment + MONTHLY_COMMENT,
            static_forcing=CMIP6_LIKE_IC_STATIC_FORCING,
            forcing_file=f"ic_{t.year:04d}-{t.month:02d}-{t.day:02d}.nc",
            **length,
            experiment_dir="/results",
            ocean_files=_monthly_files_yaml(MONTHLY_OCEAN_NAMES),
            atmos_files=_monthly_files_yaml(MONTHLY_ATMOS_NAMES_WITH_TMP2M),
        )
        name = f"inference-config-cm4-cmip6-like-ic-abrupt4xCO2-0251-{years}yr-monthly"
        (HERE / f"{name}.yaml").write_text(text)


if __name__ == "__main__":
    main()
