"""Write the 1deg coupled CM4 abrupt-4xCO2 inference configs in this directory.

Mirrors configs/experiments/cm4-like-am4-4deg-randco2v2-eval/coupled: 36
ensemble members of 90 days, branched from piControl on the first of each
month of years 0301, 0306 and 0311, plus a 100-year extension of member 1.
The ocean's time-constant forcings come from make_static_ocean_forcing.py.

Usage: python make_configs.py
"""

import pathlib

import cftime

HERE = pathlib.Path(__file__).parent
STATIC_FORCING = (
    "/climate-default/2026-11-05-cm4-abrupt-4xCO2-ensemble-1deg-static-ocean-forcing"
)
CO2_4X = 1137.048
YEARS = (301, 306, 311)

TEMPLATE = """\
# job_runner/inference.sh configs/experiments/cm4-like-am4-1deg-randco2v2-eval/coupled .
# Coupled 1deg abrupt-4xCO2 {description}: {duration} inference from piControl
# at {time}, with CO2 held at 4x ({co2} ppm). Initial conditions come from the
# daily piControl ocean store and the 6-hourly atmosphere store, since most
# first-of-month start dates are not on the 5-daily training data's time axis.
# The ocean's exogenous forcings (land_fraction, sea_surface_fraction, deptho,
# hfgeou) are time-constant, so they come from a small file that repeats them on
# a 5-day axis starting at the initial time, matching the 5-day ocean step
# (make_static_ocean_forcing.py).{extra_comment}
# Generated by make_configs.py.
experiment_dir: /results
n_coupled_steps: {n_coupled_steps} # {steps_comment}
coupled_steps_in_memory: {in_memory}
checkpoint_path: /ckpt.tar
logging:
  log_to_screen: true
  log_to_wandb: true
  log_to_file: true
  project: ace-samudra-coupled-cm4
  entity: ai2cm
initial_condition:
  ocean:
    path: /climate-default/2026-09-02-cm4-piControl-1deg-ocean-1daily.zarr
    engine: zarr
  atmosphere:
    path: /climate-default/2026-06-19-CM4-piControl-atmosphere-land-1deg-8layer-200yr.zarr
    engine: zarr
  start_indices:
    times:
      - "{time}"
forcing_loader:
  num_data_workers: 1
  ocean:
    dataset:
      data_path: {static_forcing}
      file_pattern: ic_{member:04d}.nc{ocean_repeats}
  atmosphere:
    dataset:
      merge:
        - data_path: /climate-default
          file_pattern: 2026-07-15-om4-picontrol-1deg-coupled-atmosphere.zarr
          engine: zarr{atmos_repeats}
        - data_path: /climate-default
          file_pattern: 2026-06-19-CM4-piControl-atmosphere-land-1deg-8layer-200yr.zarr
          engine: zarr{atmos_repeats}
          overwrite:
            constant:
              carbon_dioxide: {co2}
data_writer:
  ocean:
    save_prediction_files: false
    save_monthly_files: {save_monthly}{ocean_names}
  atmosphere:
    save_prediction_files: false
    save_monthly_files: {save_monthly}{atmos_names}
"""

MONTHLY_ATMOS_NAMES = [
    "air_temperature_0",
    "air_temperature_7",
    "LHTFLsfc",
    "SHTFLsfc",
    "DSWRFsfc",
    "USWRFsfc",
    "DLWRFsfc",
    "ULWRFsfc",
    "ULWRFtoa",
    "USWRFtoa",
    "surface_temperature",
    "total_frozen_precipitation_rate",
    "PRATEsfc",
]
MONTHLY_OCEAN_NAMES = [
    "hfds_total_area",
    "thetao_0",
    "thetao_18",
    "ocean_sea_ice_fraction",
]

MONTHLY_COMMENT = """
# Writes monthly means of a subset of the atmosphere and ocean outputs."""


def _names_yaml(names: list[str]) -> str:
    return "\n    names:" + "".join(f"\n      - {n}" for n in names)

EXTENSION_COMMENT = """
# Initial conditions and forcing are as in inference-config-cm4-abrupt4xCO2-ic1.yaml,
# except that both forcing datasets are repeated in time to cover 0301-0401:
# - the piControl atmosphere stores end in 0350, so they are repeated once; the
#   remaining atmosphere forcings are periodic in the noleap calendar and CO2 is
#   overwritten with a constant, so the repeat introduces no discontinuity.
# - the ocean's time-constant forcings file only spans the 150-day window on a
#   5-day axis, so it is tiled well past the 7301 times needed."""


def start_times() -> list[cftime.datetime]:
    """Initial times of ensemble members 1-36, in member order."""
    return [
        cftime.datetime(year, month, 1, calendar="noleap")
        for year in YEARS
        for month in range(1, 13)
    ]


def format_time(time: cftime.datetime) -> str:
    return f"{time.year:04d}-{time.month:02d}-{time.day:02d}T00:00:00"


def main():
    times = start_times()
    for member, time in enumerate(times, start=1):
        text = TEMPLATE.format(
            description=f"ensemble member {member} of {len(times)}",
            time=format_time(time),
            co2=CO2_4X,
            extra_comment="",
            n_coupled_steps=18,
            duration="90-day",
            steps_comment="90 days of 5-day ocean steps",
            in_memory=6,
            static_forcing=STATIC_FORCING,
            member=member,
            ocean_repeats="",
            atmos_repeats="",
            save_monthly="false",
            ocean_names="",
            atmos_names="",
        )
        (HERE / f"inference-config-cm4-abrupt4xCO2-ic{member}.yaml").write_text(text)
    for suffix, monthly in [("", False), ("-monthly", True)]:
        text = TEMPLATE.format(
            description=f"extension of ensemble member 1 of {len(times)}",
            time=format_time(times[0]),
            co2=CO2_4X,
            extra_comment=EXTENSION_COMMENT + (MONTHLY_COMMENT if monthly else ""),
            n_coupled_steps=7300,
            duration="100-year",
            steps_comment="100 years of 5-day ocean steps",
            in_memory=4,
            static_forcing=STATIC_FORCING,
            member=1,
            ocean_repeats="\n      n_repeats: 500",
            atmos_repeats="\n          n_repeats: 2",
            save_monthly="true" if monthly else "false",
            ocean_names=_names_yaml(MONTHLY_OCEAN_NAMES) if monthly else "",
            atmos_names=_names_yaml(MONTHLY_ATMOS_NAMES) if monthly else "",
        )
        name = f"inference-config-cm4-abrupt4xCO2-ic1-100yr{suffix}.yaml"
        (HERE / name).write_text(text)


if __name__ == "__main__":
    main()
