#!/usr/bin/env python3
"""Generate a one-step MLP Nino3.4 readout config on the AR SST IC set.

The original ``evaluate-coupled-nino-scalars.yaml`` picks ICs by index stride
(``first``/``interval``), which lands on 0211-0215 and drifts off calendar
month starts. This script instead writes explicit ``start_indices.times`` taken
from :func:`make_year_configs_ar_sst.monthly_ic_times`, so the MLP readout is
evaluated on the *same* ICs as the autoregressive SST rollouts and the two
skill curves are directly comparable.

Inference runs every IC as a single batch (see ``InferenceDataLoaderConfig``),
so GPU memory scales with the IC count and the full 240-IC window OOMs on one
H100. The window is therefore split into chunks of ``--chunk-size`` ICs, each
launched as its own job.

Example::

    python make_scalar_config_ar_sst_ics.py --oos-window extended20
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml
from make_year_configs_ar_sst import OOS_WINDOWS, monthly_ic_times

N_LEADS = 12
NINO_NAMES = [f"nino34_lead_{lead:02d}" for lead in range(1, N_LEADS + 1)]
# 60 ICs is the largest batch observed to fit; 240 needed ~177 GiB and OOMed.
DEFAULT_CHUNK_SIZE = 60

OCEAN_SOURCES = [
    "2025-10-21-cm4-1pctCO2-140yr-no-smoothing-coupled-ocean.zarr",
    "2025-10-16-cm4-1pctCO2-140yr-ocean-no-smoothing.zarr",
    "2026-07-14-cm4-1pctCO2-140yr-ocean-no-smoothing-nino-leads.zarr",
]
ATMOSPHERE_SOURCES = [
    "2025-10-21-cm4-1pctCO2-140yr-no-smoothing-coupled-sea_ice.zarr",
    "2025-06-18-CM4-1pctCO2-atmosphere-land-1deg-8layer-140yr.zarr",
]


def _merge(file_patterns: list[str]) -> dict:
    return {
        "merge": [
            {
                "data_path": "/climate-default",
                "file_pattern": pattern,
                "engine": "zarr",
            }
            for pattern in file_patterns
        ]
    }


def make_config(times: list[str]) -> dict:
    return {
        "experiment_dir": "/results/raw",
        "n_coupled_steps": 1,
        "coupled_steps_in_memory": 1,
        "checkpoint_path": "/ckpt.tar",
        "logging": {
            "log_to_screen": True,
            "log_to_wandb": True,
            "log_to_file": True,
            "project": "ace-samudra-coupled-cm4",
            "entity": "ai2cm",
        },
        "loader": {
            "start_indices": {"times": times},
            "dataset": {
                "ocean": _merge(OCEAN_SOURCES),
                "atmosphere": _merge(ATMOSPHERE_SOURCES),
            },
            "num_data_workers": 4,
        },
        "data_writer": {
            "ocean": {
                "save_prediction_files": True,
                "save_monthly_files": False,
                "names": NINO_NAMES,
            },
            "atmosphere": {
                "save_prediction_files": False,
                "save_monthly_files": False,
            },
        },
        "aggregator": {
            "log_histograms": False,
            "log_zonal_mean_images": False,
            "log_global_mean_time_series": False,
            "log_global_mean_norm_time_series": False,
        },
    }


def _write_config(output: Path, header: str, times: list[str]) -> None:
    with open(output, "w") as file:
        file.write(header)
        yaml.dump(make_config(times), file, sort_keys=False, default_flow_style=False)
    print(f"Wrote {output} ({len(times)} ICs, first={times[0]}, last={times[-1]})")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--oos-window",
        choices=sorted(OOS_WINDOWS),
        default="extended20",
    )
    parser.add_argument(
        "--chunk-size",
        type=int,
        default=DEFAULT_CHUNK_SIZE,
        help=(
            "ICs per job. Inference runs all ICs as one batch, so this caps GPU "
            "memory. Use 0 to emit a single unchunked config."
        ),
    )
    parser.add_argument("--output-dir", type=Path, default=None)
    args = parser.parse_args()

    year_start, year_end, note = OOS_WINDOWS[args.oos_window]
    times: list[str] = []
    for year in range(year_start, year_end + 1):
        times.extend(monthly_ic_times(year))

    output_dir = args.output_dir or Path(__file__).resolve().parent
    stem = f"evaluate-coupled-nino-scalars-{args.oos_window}"
    provenance = (
        f"# {note}.\n"
        "# ICs are identical to the AR SST rollouts so skill curves are\n"
        "# directly comparable.\n"
        "# Generated by make_scalar_config_ar_sst_ics.py; do not edit by hand.\n"
    )

    for stale in output_dir.glob(f"{stem}-chunk*.yaml"):
        stale.unlink()

    chunk_size = args.chunk_size if args.chunk_size > 0 else len(times)
    chunks = [times[i : i + chunk_size] for i in range(0, len(times), chunk_size)]
    if len(chunks) == 1:
        header = (
            f"# One-step MLP Nino3.4 readout eval, OOS window {args.oos_window}.\n"
            f"# {len(times)} monthly ICs ({year_start:04d}-{year_end:04d}).\n"
            f"{provenance}"
        )
        _write_config(output_dir / f"{stem}.yaml", header, times)
        return

    for index, chunk in enumerate(chunks):
        header = (
            f"# One-step MLP Nino3.4 readout eval, OOS window {args.oos_window}.\n"
            f"# Chunk {index + 1} of {len(chunks)}: {len(chunk)} of {len(times)}\n"
            f"# monthly ICs spanning {year_start:04d}-{year_end:04d}. Chunked because\n"
            "# inference runs all ICs as a single batch.\n"
            f"{provenance}"
        )
        _write_config(output_dir / f"{stem}-chunk{index:02d}.yaml", header, chunk)


if __name__ == "__main__":
    main()
