# ruff: noqa: E501
"""Residual sea ice under the paper-1 recipe with random-CO2 replay, at 4deg (Troy 2026-11-03).

Two arms of the paper-1 recipe (hybrid thetao residual, diagnosed SST = sst output-only, mean fill, ppad, UNCAPPED scaled
OHC corrector, NO salt corrector):
- resid-ohc-ppad-sstdiag-fmean: the control; pretrain = samudra-ppad4deg-resid-ohc-ppad-sstdiag-fmean (the CM4 arm of the
  pretrain-vs-scratch test, results 01M5X3QKC2X0BDR4CS4NK89CX7; config copied here as resid-ohc-ppad-sstdiag-fmean.yaml).
- resid-ice-ppad-sstdiag-fmean: + ocean_sea_ice_fraction / sea_ice_volume / UI / VI residual (the 4deg +ice arm of the
  partial-residual test, which was pretrained with the salt corrector and coupled without replay; this is its clean twin).
Each gets the alternating coupled fine-tune with random-CO2 atmosphere-only replay batches
(coupled/<arm>-coupled-ft-jointens-spb-rco2rs2-replay.yaml = the cap0005 replay config with the arm's own ocean stepper,
corrector warm-up off), the recipe every CM4 coupled FT uses from now on.

Launch:
  ARMS=resid-ice-ppad-sstdiag-fmean ./launch-4deg-ppad.sh                                   # pretrain, 1 GPU, 75 ep
  ATMOS_DS=01M4Z3CQXD8BF13S4X6462XVNH ARMS=<arm> VARIANT=-jointens-spb-rco2rs2-replay ./launch-4deg-ppad-coupled-ft.sh
"""

import copy
import pathlib

import yaml

HERE = pathlib.Path(__file__).resolve().parent
ICE = ["ocean_sea_ice_fraction", "sea_ice_volume", "UI", "VI"]

base = yaml.safe_load((HERE / "resid-ohc-ppad-sstdiag-fmean.yaml").read_text())
ice = copy.deepcopy(base)
ice_cfg = ice["stepper"]["step"]["config"]
assert "sst" not in ice_cfg["in_names"] and "sst" in ice_cfg["out_names"]
assert (
    "max_scaled_contraction"
    not in ice_cfg["corrector"]["config"]["ocean_heat_content_correction"]
)
assert "ocean_salt_content_correction" not in ice_cfg["corrector"]["config"]
ice_cfg["residual_prediction"]["names"] += ICE
(HERE / "resid-ice-ppad-sstdiag-fmean.yaml").write_text(
    "# resid-ice-ppad-sstdiag-fmean: the paper-1 recipe (resid-ohc-ppad-sstdiag-fmean.yaml: thetao residual, diagnosed SST,\n"
    "# mean fill, uncapped OHC corrector, no salt corrector) + sea ice (fraction, volume, UI, VI) residual. Generated by\n"
    "# make_resid_ice_replay_configs.py. Troy 2026-11-03.\n"
    + yaml.safe_dump(ice, sort_keys=False, width=120)
)

replay = yaml.safe_load(
    (
        HERE
        / "coupled/resid-ohc-cap0005-ppad-coupled-ft-jointens-spb-rco2rs2-replay.yaml"
    ).read_text()
)
for arm, pre in (
    ("resid-ohc-ppad-sstdiag-fmean", base),
    ("resid-ice-ppad-sstdiag-fmean", ice),
):
    c = copy.deepcopy(replay)
    c["logging"]["metrics_log_dir"] = (
        "metrics"  # this branch requires a path relative to experiment_dir
    )
    ocean = copy.deepcopy(pre["stepper"])
    ocean["step"]["config"]["corrector"]["config"]["corrector_disabled_epochs"] = 0
    c["stepper"]["ocean"]["stepper"] = ocean
    n_res = len(ocean["step"]["config"]["residual_prediction"]["names"])
    (HERE / f"coupled/{arm}-coupled-ft-jointens-spb-rco2rs2-replay.yaml").write_text(
        f"# {arm}-coupled-ft-jointens-spb-rco2rs2-replay: alternating coupled fine-tune with random-CO2 atmosphere-only replay\n"
        f"# batches (= resid-ohc-cap0005-ppad-coupled-ft-jointens-spb-rco2rs2-replay.yaml) of the {arm} ocean ({n_res} residual\n"
        f"# names, diagnosed SST, mean fill, uncapped OHC corrector, no salt corrector; corrector warm-up off) with the random-CO2\n"
        f"# ACE2S rs2 atmosphere (01M4Z3CQXD8BF13S4X6462XVNH). Generated by make_resid_ice_replay_configs.py. Troy 2026-11-03.\n"
        + yaml.safe_dump(c, sort_keys=False, width=120)
    )
    print(
        "wrote",
        arm,
        "| residual names",
        n_res,
        "| fill",
        ocean["input_masking"]["fill_value"],
    )
