"""Generate the restoring-force experiment configs (run from this directory).

Stage A (evaluator-states.yaml): 5-year rollout from the 8 1940 ICs saving the
full prognostic state every 73 days (25 snapshots x 8 ICs = 200 states).
Stage B (inference-<source>-states-c<i>.yaml): 30-day runs from 50 of those
saved states (source = the checkpoint whose rollout produced them).
Stage C (evaluator-era5-states-c<i>.yaml): 30-day runs from the ERA5 states on
the same dates. Stages B/C save 5-day-mean maps per state.
"""

import datetime

import yaml

PROGNOSTIC = (
    ["PRESsfc", "surface_temperature"]
    + [
        f"{name}_{i}"
        for name in (
            "air_temperature",
            "specific_total_water",
            "eastward_wind",
            "northward_wind",
        )
        for i in range(8)
    ]
)
SAVED = (
    [f"air_temperature_{i}" for i in range(8)]
    + ["specific_total_water_0", "PRESsfc", "TMP2m", "ULWRFtoa", "USWRFtoa"]
    + ["PRATEsfc"]
)
DATASET = {
    "merge": [
        {
            "data_path": "/climate-default/",
            "file_pattern": f"{name}-era5-1deg-8layer-daily-1940-2025.zarr",
            "engine": "zarr",
        }
        for name in ("2026-08-13", "2026-07-24")
    ]
}
LOGGING = {
    "log_to_screen": True,
    "log_to_wandb": True,
    "log_to_file": True,
    "project": "ace",
    "entity": "ai2cm",
}
IC_DATES = [datetime.datetime(1940, 1, 3 + i) for i in range(8)]
SNAPSHOT_INTERVAL = 73
N_SNAPSHOTS = 25
N_CHUNKS = 4
CHUNK = len(IC_DATES) * N_SNAPSHOTS // N_CHUNKS
SHORT_STEPS = 30
COARSEN = 5


def fmt(t):
    return t.strftime("%Y-%m-%dT%H:%M:%S")


def short_writer(save_reference):
    return {
        "save_prediction_files": False,
        "save_monthly_files": False,
        "files": [
            {
                "label": "5day_mean",
                "names": SAVED,
                "save_reference": save_reference,
                "time_coarsen": {"coarsen_factor": COARSEN},
            }
        ],
    }


def write(name, header, config):
    with open(name, "w") as f:
        f.write("".join(f"# {line}\n" for line in header))
        f.write("# Generated by make_configs.py; edit that, not this file.\n")
        yaml.safe_dump(config, f, sort_keys=False)


def main():
    write(
        "evaluator-states.yaml",
        [
            "Stage A: 5-year rollout from the 8 1940 ICs, saving the full",
            "prognostic state every 73 days. forward_steps_in_memory equals the",
            "snapshot interval so the step slice picks one state per window.",
        ],
        {
            "experiment_dir": "/results",
            "n_forward_steps": SNAPSHOT_INTERVAL * N_SNAPSHOTS,
            "forward_steps_in_memory": SNAPSHOT_INTERVAL,
            "checkpoint_path": "/ckpt.tar",
            "n_ensemble_per_ic": 1,
            "logging": LOGGING,
            "loader": {
                "dataset": DATASET,
                "start_indices": {"times": [fmt(t) for t in IC_DATES]},
                "num_data_workers": 4,
            },
            "data_writer": {
                "save_prediction_files": False,
                "save_monthly_files": False,
                "files": [
                    {
                        "label": "states",
                        "names": PROGNOSTIC,
                        "save_reference": False,
                        "time_selection": {"start": 0, "step": SNAPSHOT_INTERVAL},
                    }
                ],
            },
        },
    )
    # state order in the stage-A-derived IC files: IC-major, snapshot-minor
    era5_times = [
        ic + datetime.timedelta(days=SNAPSHOT_INTERVAL * k)
        for ic in IC_DATES
        for k in range(1, N_SNAPSHOTS + 1)
    ]
    for i in range(N_CHUNKS):
        write(
            f"evaluator-era5-states-c{i}.yaml",
            [
                f"Stage C chunk {i}: 30-day runs from the ERA5 states on the dates",
                "of the stage-A snapshots (IC date + 73 k days).",
            ],
            {
                "experiment_dir": "/results",
                "n_forward_steps": SHORT_STEPS,
                "forward_steps_in_memory": COARSEN,
                "checkpoint_path": "/ckpt.tar",
                "n_ensemble_per_ic": 1,
                "logging": LOGGING,
                "loader": {
                    "dataset": DATASET,
                    "start_indices": {
                        "times": [
                            fmt(t) for t in era5_times[i * CHUNK : (i + 1) * CHUNK]
                        ]
                    },
                    "num_data_workers": 4,
                },
                "data_writer": short_writer(save_reference=True),
            },
        )
        for source in ("ep120", "ep20"):
            write(
                f"inference-{source}-states-c{i}.yaml",
                [
                    f"Stage B chunk {i}: 30-day runs from states saved along the",
                    f"{source} checkpoint's stage-A rollout (mounted at /ic).",
                ],
                {
                    "experiment_dir": "/results",
                    "n_forward_steps": SHORT_STEPS,
                    "forward_steps_in_memory": COARSEN,
                    "checkpoint_path": "/ckpt.tar",
                    "n_ensemble_per_ic": 1,
                    "logging": LOGGING,
                    "initial_condition": {
                        "path": f"/ic/{source}-states.nc",
                        "start_indices": {
                            "first": i * CHUNK,
                            "n_initial_conditions": CHUNK,
                            "interval": 1,
                        },
                    },
                    "forcing_loader": {"dataset": DATASET, "num_data_workers": 4},
                    "data_writer": short_writer(save_reference=False),
                },
            )


if __name__ == "__main__":
    main()
