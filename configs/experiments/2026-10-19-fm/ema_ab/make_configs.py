"""Write the EMA foreach A/B test configs (ai2cm/ace#1611) into this directory.

Same reduction as cudagraphs_ab: the seed-2, mask-on nc-swin-v2.2 run config
reduced to ERA5 only (train, validation and inline inference; the c96
inference entries are dropped since no c96 data is trained on), run for 2
epochs with every inline inference at epoch 2. The SFNO config is the same
with only the builder swapped for the SFNO twin's.

The arms share these configs and differ only in code: the "foreach" arm runs
from the commit that adds this directory (fme/core/ema.py as in #1611), the
"repo" arm from the next commit, which restores the per-parameter EMA loop
from main.
"""

import pathlib

import yaml

HERE = pathlib.Path(__file__).parent
SOURCE = (
    HERE.parent
    / "run_configs"
    / "ace-train-config-4deg-nc-swin-v2.2-fm-a2-cond-era5-c96-piC-1pct-cm4-xshield"
    "-s2-maskon.yaml"
)
SFNO_SOURCE = (
    HERE.parent
    / "run_configs"
    / "ace-train-config-4deg-nc-sfno-fm-a2-cond-era5-c96-piC-1pct-cm4-xshield"
    "-s2-maskon.yaml"
)
ERA5_LABEL = "era5"
MAX_EPOCHS = 2


def _is_era5(dataset: dict) -> bool:
    return dataset["labels"] == [ERA5_LABEL]


def _era5_only(config: dict) -> dict:
    config["max_epochs"] = MAX_EPOCHS
    train = config["train_loader"]["dataset"]
    train["concat"] = [d for d in train["concat"] if _is_era5(d)]
    validation = config["validation"]["loader"]["dataset"]
    validation["concat"] = [d for d in validation["concat"] if _is_era5(d)]
    inference = [e for e in config["inference"] if _is_era5(e["loader"]["dataset"])]
    for entry in inference:
        # training epochs are 1..max_epochs, so start 1 selects epoch 2 only
        entry["epochs"] = {"start": MAX_EPOCHS - 1}
    config["inference"] = inference
    return config


def _builder(config: dict) -> dict:
    return config["stepper"]["step"]["config"]["builder"]


def main():
    sfno_builder = _builder(yaml.safe_load(SFNO_SOURCE.read_text()))
    for arch in ["swin", "sfno"]:
        config = _era5_only(yaml.safe_load(SOURCE.read_text()))
        if arch == "sfno":
            config["stepper"]["step"]["config"]["builder"] = sfno_builder
        (HERE / f"ema-ab-{arch}.yaml").write_text(
            f"# EMA foreach A/B test config ({arch}); generated by make_configs.py\n"
            + yaml.safe_dump(config, sort_keys=False)
        )


if __name__ == "__main__":
    main()
