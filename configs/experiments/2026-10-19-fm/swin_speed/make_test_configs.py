"""Write the Swin speed-study training test configs into this directory.

Each is the seed-1, mask-off nc-swin-v2.2 run config with max_epochs 3 (the
LR warmup is per epoch, so epoch 3 is the first at full LR) and one
architecture or compile-mode change.
"""

import pathlib

HERE = pathlib.Path(__file__).parent
SOURCE = (
    HERE.parent
    / "run_configs"
    / "ace-train-config-4deg-nc-swin-v2.2-fm-a2-cond-era5-c96-piC-1pct-cm4-xshield"
    "-s1-maskoff.yaml"
)
SFNO_SOURCE = (
    HERE.parent
    / "run_configs"
    / "ace-train-config-4deg-nc-sfno-fm-a2-cond-era5-c96-piC-1pct-cm4-xshield"
    "-s1-maskoff.yaml"
)
BASE_BUILDER = """          embed_dim: 192
          noise_embed_dim: 32
          depth_multiplier: 2
          num_heads:
          - 3
          - 6
          - 6
          - 3
"""
DM1_E256_BUILDER = """          embed_dim: 256
          noise_embed_dim: 32
          depth_multiplier: 1
          num_heads:
          - 4
          - 8
          - 8
          - 4
"""
CUDA_GRAPHS = "# arg: --env FME_COMPILE_MODE=reduce-overhead\n"

VARIANTS = {
    # v2.2 as is: measures the EMA change alone under DDP
    "base": ("", None),
    # v2.2 with CUDA graphs
    "base-ro": (CUDA_GRAPHS, None),
    # half the blocks, wider; drop_path_rate halved to keep the per-block max
    "dm1e256": ("", DM1_E256_BUILDER),
    "dm1e256-ro": (CUDA_GRAPHS, DM1_E256_BUILDER),
}


def main():
    text = SOURCE.read_text()
    assert text.count(BASE_BUILDER) == 1
    assert text.count("max_epochs: 150\n") == 1
    assert text.count("          drop_path_rate: 0.2\n") == 1
    for name, (header, builder) in VARIANTS.items():
        out = text.replace("max_epochs: 150\n", "max_epochs: 3\n")
        if builder is not None:
            out = out.replace(BASE_BUILDER, builder).replace(
                "          drop_path_rate: 0.2\n", "          drop_path_rate: 0.1\n"
            )
        out = (
            f"# Swin speed study test config ({name}); generated by "
            "make_test_configs.py\n" + header + out
        )
        (HERE / f"swin-speed-{name}-s1.yaml").write_text(out)
    # SFNO twin on the same hardware, for a throughput reference
    sfno = SFNO_SOURCE.read_text()
    assert sfno.count("max_epochs: 150\n") == 1
    (HERE / "swin-speed-sfno-s1.yaml").write_text(
        "# Swin speed study test config (SFNO reference); generated by "
        "make_test_configs.py\n" + sfno.replace("max_epochs: 150\n", "max_epochs: 3\n")
    )


if __name__ == "__main__":
    main()
