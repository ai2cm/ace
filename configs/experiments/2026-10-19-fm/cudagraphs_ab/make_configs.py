"""Write the CUDA graphs A/B test configs (ai2cm/ace#1610) into this directory.

Both arms are the seed-2, mask-on nc-swin-v2.2 run config reduced to ERA5
only (train, validation and inline inference; the c96 inference entries are
dropped since no c96 data is trained on), run for 2 epochs with every inline
inference at epoch 2. The arms differ only in FME_COMPILE_MODE: "on" uses the
default reduce-overhead mode (CUDA graphs), "off" sets FME_COMPILE_MODE=default
(inductor without CUDA graphs).

The SFNO pair is the same config with only the builder swapped for the SFNO
twin's, so it keeps the Swin cell's optimizer schedule, non-finite-loss guard
and TF32 matmuls.
"""

import pathlib

import yaml

HERE = pathlib.Path(__file__).parent
SOURCE = (
    HERE.parent
    / "run_configs"
    / "ace-train-config-4deg-nc-swin-v2.2-fm-a2-cond-era5-c96-piC-1pct-cm4-xshield"
    "-s2-maskon.yaml"
)
SFNO_SOURCE = (
    HERE.parent
    / "run_configs"
    / "ace-train-config-4deg-nc-sfno-fm-a2-cond-era5-c96-piC-1pct-cm4-xshield"
    "-s2-maskon.yaml"
)
ERA5_LABEL = "era5"
MAX_EPOCHS = 2

ARMS = {
    "on": "",
    "off": "# arg: --env FME_COMPILE_MODE=default\n",
}


def _is_era5(dataset: dict) -> bool:
    return dataset["labels"] == [ERA5_LABEL]


def _era5_only(config: dict) -> dict:
    config["max_epochs"] = MAX_EPOCHS
    train = config["train_loader"]["dataset"]
    train["concat"] = [d for d in train["concat"] if _is_era5(d)]
    validation = config["validation"]["loader"]["dataset"]
    validation["concat"] = [d for d in validation["concat"] if _is_era5(d)]
    inference = [e for e in config["inference"] if _is_era5(e["loader"]["dataset"])]
    for entry in inference:
        # training epochs are 1..max_epochs, so start 1 selects epoch 2 only
        entry["epochs"] = {"start": MAX_EPOCHS - 1}
    config["inference"] = inference
    return config


def _builder(config: dict) -> dict:
    return config["stepper"]["step"]["config"]["builder"]


def main():
    sfno_builder = _builder(yaml.safe_load(SFNO_SOURCE.read_text()))
    for arch, prefix in [("swin", "cudagraphs-ab"), ("sfno", "cudagraphs-ab-sfno")]:
        for arm, header in ARMS.items():
            config = _era5_only(yaml.safe_load(SOURCE.read_text()))
            if arch == "sfno":
                config["stepper"]["step"]["config"]["builder"] = sfno_builder
            (HERE / f"{prefix}-{arm}.yaml").write_text(
                f"# CUDA graphs A/B test config ({arch}, {arm}); generated by "
                "make_configs.py\n" + header + yaml.safe_dump(config, sort_keys=False)
            )


if __name__ == "__main__":
    main()
