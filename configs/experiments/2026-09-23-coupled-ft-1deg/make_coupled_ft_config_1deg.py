#!/usr/bin/env python
"""Compose the 1deg coupled fine-tune config for the piC+1pct hybrid-residual ocean.

The team's coupled fine-tunes
(cm4_1pctCO2-1pct_45to125_piC_156to235-coupled-<ocean>_a2s-fto, ace branch
exper/2026-07-16-jamesd @05fefd314) are the shared 1deg coupled train template
with an ocean arm's `stepper` block spliced in as stepper.ocean.stepper and the
1deg ACE2S atmosphere's as stepper.atmosphere.stepper; 8 epochs, lr 7e-5, the
atmosphere frozen. This does the same for Elynn's hybrid-residual ocean
(cm4_1pct_46to125_piC_156to235-ocean_wide_hybridresid_clip1_sstff_ohc-ft, ace
branch exper/2026-09-11-hybridresid-noclip-sstff-ohc @a476a30ec): the same 97
inputs, 87 outputs, Samudra builder and correctors as the team's oceans,
differing only in predicting thetao_0..18 as normalized residuals. Its config
carries the pre-#1487 flat residual keys, converted to the {names, normalized}
block here.

Two variants, mirroring the team's pair for the deterministic ohc_clip ocean:
  ens : EnsembleLoss (CRPS 0.9 + energy score 0.1), two members
        (their default, "owc" and "owc8")
  mse : MSE, one member (their "coupled_mse-owc")

    python make_coupled_ft_config_1deg.py ens
    # -> hybridresid-pic1pct-coupled-ft-ens.yaml
"""

import argparse
import copy
import pathlib

import yaml

HERE = pathlib.Path(__file__).resolve().parent
TEMPLATE = HERE / "train-config-template-1deg.yaml"
ATMOS = HERE / "atmos-ace2s-ft-1deg-stepper.yaml"
OCEAN = HERE / "ocean-hybridresid-pic1pct-ft8.yaml"
STRIP = (
    "loss",
    "optimize_last_step_only",
    "n_ensemble",
    "parameter_init",
    "train_n_forward_steps",
)


def merge_template_wins(template: dict, incoming: dict) -> dict:
    """Deep-merge ``incoming`` under ``template``; template keys win on conflict."""
    out = copy.deepcopy(incoming)
    for k, v in template.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = merge_template_wins(v, out[k])
        else:
            out[k] = copy.deepcopy(v)
    return out


def convert_residual_schema(step_config: dict) -> None:
    """pre-#1487 flat keys -> residual_prediction: {names, normalized}."""
    if isinstance(step_config.get("residual_prediction"), dict):
        return
    flag = step_config.pop("residual_prediction", False)
    names = step_config.pop("residual_prediction_names", None)
    normalized = step_config.pop("residual_normalized_prediction", True)
    if flag or names:
        step_config["residual_prediction"] = {
            "names": list(names) if names else None,
            "normalized": bool(normalized),
        }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("variant", choices=["ens", "mse"])
    args = ap.parse_args()

    cfg = yaml.safe_load(TEMPLATE.read_text())
    ocean = yaml.safe_load(OCEAN.read_text())["stepper"]
    atmos = yaml.safe_load(ATMOS.read_text())["stepper"]
    for comp in (ocean, atmos):
        for k in STRIP:
            comp.pop(k, None)
    convert_residual_schema(ocean["step"]["config"])

    cfg["stepper"]["ocean"]["stepper"] = merge_template_wins(
        cfg["stepper"]["ocean"].get("stepper") or {}, ocean
    )
    cfg["stepper"]["atmosphere"]["stepper"] = merge_template_wins(
        cfg["stepper"]["atmosphere"].get("stepper") or {}, atmos
    )
    corr = ocean["step"]["config"]["corrector"]["config"]
    sic = corr["sea_ice_fraction_correction"]["sea_ice_fraction_name"]
    cfg["stepper"]["ocean_fraction_prediction"]["sea_ice_fraction_name"] = sic
    if args.variant == "mse":
        cfg["stepper_training"]["n_ensemble"] = 1
        cfg["stepper_training"]["ocean"]["loss"] = {"type": "MSE"}

    loss_note = (
        "EnsembleLoss, two members (their default)"
        if args.variant == "ens"
        else "MSE, one member (their coupled_mse variant)"
    )
    out = HERE / f"hybridresid-pic1pct-coupled-ft-{args.variant}.yaml"
    header = "\n".join(
        [
            f"# hybridresid-pic1pct-coupled-ft-{args.variant}: 1deg coupled FT of",
            "# Elynn's piControl+1pctCO2 hybrid-residual ocean (thetao_0..18 residual,",
            "# sst full-field, scaled_temperature OHC corrector, 8-step fine-tuned)",
            "# against the frozen 1deg ACE2S atmosphere, on the team's coupled recipe",
            "# (8 epochs, lr 7e-5, 4 coupled steps, atmosphere frozen with no loss).",
            "# Generated by make_coupled_ft_config_1deg.py; see its docstring.",
            f"# Ocean loss: {loss_note}.",
            "",
        ]
    )
    out.write_text(header + yaml.safe_dump(cfg, sort_keys=False, width=100))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
