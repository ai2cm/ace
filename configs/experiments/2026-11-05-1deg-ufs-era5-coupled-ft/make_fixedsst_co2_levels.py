#!/usr/bin/env python
"""Extra CO2 levels for the fixed-SST runs of the CM4-line ACE2.5 atmospheres.

The coupled SSP2-4.5 run keeps SST flat while CO2 rises from about 400 to 460 ppm
and the heat flux into the ocean falls. These members repeat the 400 ppm
fixed-SST run (ssp/ace2p5-fixedsst-co2-400ppm.yaml) with carbon_dioxide held at
levels the SSP ramp passes through, so the flux response to CO2 alone can be read
at identical SST.

    python make_fixedsst_co2_levels.py  -> ssp/ace2p5-fixedsst-co2-<ppm>ppm.yaml
"""

import pathlib
from typing import Any

import yaml

HERE = pathlib.Path(__file__).resolve().parent
LEVELS_PPM = [430, 460, 500, 550]
base: dict[str, Any] = yaml.safe_load(
    (HERE / "ssp/ace2p5-fixedsst-co2-400ppm.yaml").read_text()
)
base["data_writer"]["names"] += ["air_temperature_1", "PRMSL"]
for ppm in LEVELS_PPM:
    merge = base["forcing_loader"]["dataset"]["merge"]
    merge[1]["overwrite"]["constant"]["carbon_dioxide"] = float(ppm)
    header = (
        "# Fixed-SST member of the CM4-line ACE2.5 atmospheres: 10-yr prescribed-SST"
        f" run with carbon_dioxide held at {ppm} ppmv.\n"
        "# Generated by make_fixedsst_co2_levels.py; launch with"
        " launch-1deg-era5-ace2p5-fixedsst-co2.sh.\n"
    )
    (HERE / f"ssp/ace2p5-fixedsst-co2-{ppm}ppm.yaml").write_text(
        header + yaml.safe_dump(base, sort_keys=True, width=120)
    )
    print("wrote", ppm)

# Energy corrector off at inference (Troy 2026-11-23: is the reflected-shortwave
# response to CO2 tied to the energy corrector?): the checkpoint's corrector with
# total_energy_budget_correction removed, everything else kept.
NOEC_CORRECTOR = {
    "type": "atmosphere_corrector",
    "config": {
        "conserve_dry_air": True,
        "moisture_budget_correction": "advection_and_precipitation",
        "clip_frozen_precipitation": True,
        "force_positive_names": [f"specific_total_water_{i}" for i in range(8)]
        + ["Q2m", "PRATEsfc", "total_frozen_precipitation_rate"]
        + ["ULWRFsfc", "ULWRFtoa"]
        + ["DLWRFsfc", "DSWRFsfc", "USWRFsfc", "USWRFtoa"],
    },
}
for level in ["400ppm", "460ppm", "550ppm"]:
    c = yaml.safe_load((HERE / f"ssp/ace2p5-fixedsst-co2-{level}.yaml").read_text())
    c["stepper_override"]["corrector"] = NOEC_CORRECTOR
    (HERE / f"ssp/ace2p5-fixedsst-co2-{level}-noec.yaml").write_text(
        f"# As ace2p5-fixedsst-co2-{level}.yaml, energy corrector off at inference.\n"
        + yaml.safe_dump(c, sort_keys=True, width=120)
    )
    print("wrote noec", level)

# Uniform SST warming at constant CO2 (Troy 2026-11-25: the SST sensitivity of the
# CM4-only, SHiELD-fine-tuned and ERA5-fine-tuned atmospheres): the 400 ppm run
# with every ocean cell's surface temperature raised by 2 or 4 K in the forcing
# and the initial condition. The control is ace2p5-fixedsst-co2-400ppm.yaml.
for dk in [2, 4]:
    c = yaml.safe_load((HERE / "ssp/ace2p5-fixedsst-co2-400ppm.yaml").read_text())
    c["forcing_loader"]["perturbations"] = {
        "sst": [{"type": "constant", "config": {"amplitude": float(dk)}}]
    }
    (HERE / f"ssp/ace2p5-fixedsst-co2-400ppm-p{dk}k.yaml").write_text(
        f"# As ace2p5-fixedsst-co2-400ppm.yaml, with SST raised uniformly by {dk} K"
        " (launch with CFG_SUFFIX=-p{dk}k LEVELS=400ppm).\n".replace("{dk}", str(dk))
        + yaml.safe_dump(c, sort_keys=True, width=120)
    )
    print("wrote sst +", dk)
