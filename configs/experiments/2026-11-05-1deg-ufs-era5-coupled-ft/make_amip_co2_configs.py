#!/usr/bin/env python
"""AMIP-style runs of the CM4-line ACE2.5 atmospheres with and without the CO2 rise.

Troy 2026-11-25: "AMIP SSTs with constant 1979 CO2". Each atmosphere runs alone from
the ERA5 state of 1979-01-01 to the end of 2025 over the observed (ERA5) SST, sea
ice and insolation. One member sees the historical carbon_dioxide; the other has it
held at its 1979 annual mean. The difference between the two is what the model
attributes to CO2 at identical SST; the constant-CO2 member alone shows how much of
the historical change it produces from SST.

    python make_amip_co2_configs.py  -> ssp/ace2p5-amip-1979-2025-co2-{actual,1979}.yaml

Launch with launch-1deg-era5-ace2p5-amip-co2.sh.
"""

import copy
import pathlib
from typing import Any

import pandas as pd
import yaml

HERE = pathlib.Path(__file__).resolve().parent
START = "1979-01-01T00:00:00"
END = "2025-12-31T18:00:00"
IN_MEMORY = 40
CO2_1979_PPM = 336.67  # 1979 annual mean of global_mean_co2 x 1e6 in the ERA5 store
n_max = int((pd.Timestamp(END) - pd.Timestamp(START)) / pd.Timedelta("6h"))

base: dict[str, Any] = yaml.safe_load(
    (HERE / "ssp/ace2p5-fixedsst-co2-400ppm.yaml").read_text()
)
base["n_forward_steps"] = n_max // IN_MEMORY * IN_MEMORY
base["initial_condition"]["start_indices"]["times"] = [START]
base["data_writer"]["names"] += ["air_temperature_1", "PRMSL"]
base["forcing_loader"]["dataset"] = {
    "merge": [
        {
            "data_path": "/climate-default",
            "file_pattern": "2026-03-19-era5-1deg-8layer-1940-2025.zarr",
            "engine": "zarr",
            "overwrite": {"multiply_scalar": {"PRMSL": 0.01}},
        },
        {
            "data_path": "/extra",
            "file_pattern": "ace2p5_era5_extra.zarr",
            "engine": "zarr",
        },
    ]
}
for tag, co2 in [("actual", None), ("1979", CO2_1979_PPM)]:
    c = copy.deepcopy(base)
    if co2 is not None:
        c["forcing_loader"]["dataset"]["merge"][1]["overwrite"] = {
            "constant": {"carbon_dioxide": co2}
        }
    what = (
        "historical carbon_dioxide"
        if co2 is None
        else f"carbon_dioxide held at {co2} ppmv (its 1979 mean)"
    )
    (HERE / f"ssp/ace2p5-amip-1979-2025-co2-{tag}.yaml").write_text(
        "# AMIP-style run of a CM4-line ACE2.5 atmosphere, 1979-01-01 .. 2025, ERA5 SST"
        f" and sea ice, {what}.\n"
        "# Generated by make_amip_co2_configs.py; launch with"
        " launch-1deg-era5-ace2p5-amip-co2.sh.\n"
        + yaml.safe_dump(c, sort_keys=True, width=120)
    )
    print("wrote", tag, c["n_forward_steps"])
