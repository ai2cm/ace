#!/usr/bin/env python
# ruff: noqa: E501
"""fme.coupled.inference configs for SSP2-4.5 coupled runs of the 1deg UFS + ERA5 SamudrACE (Troy 2026-11-13).

Start from the observed 2015-01-20T18 state (UFS replay ocean, ERA5 atmosphere; the first 5-daily ocean stamp after the
SSP store's CO2 becomes finite on 2015-01-16T12) and run 6200 coupled steps (5-day ocean steps, 6-hourly atmosphere) to
2099-12-05 under the CM4 SSP2-4.5 CO2 path. Forcing read from disk: the atmosphere's DSWRFtoa (ERA5 2015-2025 tiled),
global_mean_co2 (CM4 SSP2-4.5), HGTsfc and land_fraction from the 2026-04-07 SSP2-4.5 ACE forcing store on weka; the
ocean's statics (land_fraction, sea_surface_fraction, deptho, hfgeou = the CM4 geothermal map used by the cm4vars store) from
a small 5-daily store built by this experiment (Beaker dataset, mounted at /oceanforcing). Ocean and sea-ice fractions reach
the atmosphere through the coupled stepper's ocean_fraction_prediction, as in training. Monthly means are written.

    python make_ssp245_configs.py
"""

import pathlib

import yaml

HERE = pathlib.Path(__file__).resolve().parent
START = "2015-01-20T18:00:00"
N_STEPS = 6200  # 5-day steps -> 2099-12-05T18; a multiple of coupled_steps_in_memory
ARMS = {
    # tag: description (checkpoint given at launch, see launch-1deg-ufs-era5-ssp245.sh)
    "noohc-fto-mse": "corrector-free ocean, MSE FTO only (6-hourly ACE2S)",
    "ohc-uhm1p7-fto-then-ftalt": "corrector-kept ocean with -1.7 W/m2 unaccounted heating trained in, CRPS FTO then Elynn alternating (6-hourly ACE2S)",
}
cfg = {
    "experiment_dir": "/results",
    "n_coupled_steps": N_STEPS,
    "coupled_steps_in_memory": 10,
    "checkpoint_path": "/ckpt.tar",
    "logging": {
        "log_to_screen": True,
        "log_to_wandb": True,
        "log_to_file": True,
        "project": "ace-samudra-coupled-cm4",
        "entity": "ai2cm",
    },
    "initial_condition": {
        "ocean": {
            "path": "/climate-default/2026-10-06-ufs-replay-ocean-1deg-19level-1994-2023-cm4vars.zarr",
            "engine": "zarr",
        },
        "atmosphere": {
            "path": "/climate-default/2026-03-19-era5-1deg-8layer-1940-2025.zarr",
            "engine": "zarr",
        },
        "start_indices": {"times": [START]},
    },
    "forcing_loader": {
        "num_data_workers": 2,
        "atmosphere": {
            "dataset": {
                "data_path": "/climate-default",
                "file_pattern": "2026-04-07-cm4-ssp245-ACE-forcing-dataset.zarr",
                "engine": "zarr",
            }
        },
        "ocean": {
            "dataset": {
                "data_path": "/oceanforcing",
                "file_pattern": "ocean_forcing_ssp245.zarr",
                "engine": "zarr",
            }
        },
    },
    "data_writer": {
        "ocean": {
            "save_prediction_files": False,
            "save_monthly_files": True,
            "names": [
                "sst",
                "thetao_0",
                "thetao_5",
                "thetao_10",
                "thetao_18",
                "so_0",
                "ocean_sea_ice_fraction",
                "sea_ice_volume",
                "hfds_total_area",
                "zos",
            ],
        },
        "atmosphere": {
            "save_prediction_files": False,
            "save_monthly_files": True,
            "names": [
                "surface_temperature",
                "TMP2m",
                "PRESsfc",
                "PRATEsfc",
                "DSWRFsfc",
                "DLWRFsfc",
                "ULWRFsfc",
                "USWRFsfc",
                "LHTFLsfc",
                "SHTFLsfc",
                "DSWRFtoa",
                "ULWRFtoa",
                "USWRFtoa",
                "eastward_surface_stress",
                "northward_surface_stress",
                "sea_ice_fraction",
                "ocean_fraction",
                "h500",
                "TMP850",
            ],
        },
    },
    "aggregator": {"log_global_mean_time_series": True},
}
for tag, desc in ARMS.items():
    h = f"# SSP2-4.5 coupled run 2015-01-20 .. 2099-12-05 (6200 coupled steps) of the 1deg UFS + ERA5 SamudrACE: {desc}.\n# Generated by make_ssp245_configs.py; launch with launch-1deg-ufs-era5-ssp245.sh.\n"
    (HERE / f"ssp/ufs1deg-ssp245-{tag}.yaml").write_text(
        h + yaml.safe_dump(cfg, sort_keys=False, width=120)
    )
    print("wrote", tag)
