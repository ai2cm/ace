#!/usr/bin/env python
# ruff: noqa: E501
"""fme.ace.inference configs for ATMOSPHERE-ONLY SSP2-4.5 runs of the 1deg 6-hourly ACE2S with prescribed SST (Troy 2026-11-13:
"take out the atmosphere weights and force with the SSTs I made from the SSP4.5 forcing file").

The atmosphere runs alone from the ERA5 state of 2015-01-20T18 (the coupled SSP runs' start) to 2099-12-31 under the 2026-04-07
SSP2-4.5 ACE forcing store on weka: DSWRFtoa (ERA5 2015-2025 tiled), global_mean_co2 (CM4 SSP2-4.5), HGTsfc, land_fraction,
and the prescribed surface_temperature (ERA5 climatology + CM4 SSP2-4.5 SST anomaly over ocean), ocean_fraction and
sea_ice_fraction (ERA5 climatology + CM4 anomaly). The checkpoint's own ocean config (surface_temperature over ocean_fraction)
overwrites the ocean surface temperature from the forcing every step. Two atmospheres: the original ACE2S 6-hourly checkpoint
(= the MSE FTO arm's atmosphere, which FTO leaves frozen) and the atmosphere lifted out of the corrector-kept -1.7 alternating
arm's coupled checkpoint (scripts/coupled/create_decoupled_checkpoint.py). Monthly means written.

    python make_ssp245_atmos_configs.py
"""

import copy
import pathlib
from typing import Any

import pandas as pd
import yaml

HERE = pathlib.Path(__file__).resolve().parent
START = "2015-01-20T18:00:00"
END = "2099-12-31T18:00:00"
IN_MEMORY = 40
n_max = int((pd.Timestamp(END) - pd.Timestamp(START)) / pd.Timedelta("6h"))
N_STEPS = n_max // IN_MEMORY * IN_MEMORY
ARMS = {
    "ace2s6h-original": "the original ACE2S 6-hourly checkpoint (the MSE FTO arm's atmosphere, frozen in FTO)",
    "ohc-uhm1p7-fto-then-ftalt-atmosphere": "the atmosphere lifted from the corrector-kept -1.7 W/m2 CRPS FTO then Elynn alternating coupled checkpoint",
}
cfg: dict[str, Any] = {
    "experiment_dir": "/results",
    "n_forward_steps": N_STEPS,
    "forward_steps_in_memory": IN_MEMORY,
    "checkpoint_path": "/ckpt.tar",
    "logging": {
        "log_to_screen": True,
        "log_to_wandb": True,
        "log_to_file": True,
        "project": "ace-samudra-coupled-cm4",
        "entity": "ai2cm",
    },
    "initial_condition": {
        "path": "/climate-default/2026-03-19-era5-1deg-8layer-1940-2025.zarr",
        "engine": "zarr",
        "start_indices": {"times": [START]},
    },
    "forcing_loader": {
        "num_data_workers": 2,
        "dataset": {
            "data_path": "/climate-default",
            "file_pattern": "2026-04-07-cm4-ssp245-ACE-forcing-dataset.zarr",
            "engine": "zarr",
        },
    },
    "data_writer": {
        "save_prediction_files": False,
        "save_monthly_files": True,
        "names": [
            "surface_temperature",
            "TMP2m",
            "PRESsfc",
            "PRATEsfc",
            "DSWRFsfc",
            "DLWRFsfc",
            "ULWRFsfc",
            "USWRFsfc",
            "LHTFLsfc",
            "SHTFLsfc",
            "DSWRFtoa",
            "ULWRFtoa",
            "USWRFtoa",
            "sea_ice_fraction",
            "ocean_fraction",
            "h500",
            "TMP850",
            "air_temperature_7",
            "air_temperature_0",
        ],
    },
    "aggregator": {"log_global_mean_time_series": True},
}
# The CM4-line ACE2.5 (Spencer's ace2p5 rs1, trained on CM4 random-CO2 data; Troy 2026-11-13 "also use the original ACE2.5 ckpt
# before it was coupled FTed") reads carbon_dioxide in ppmv and a lake_fraction, which the SSP store lacks: they come from a small
# extra store on the SSP time axis (carbon_dioxide = global_mean_co2 x 1e6, lake_fraction = the CM4 static map), merged in.
# Coordinates are named latitude/longitude in the ERA5-based stores and lat/lon in the CM4 training data (same values), hence
# allow_incompatible_dataset. The SSP store's ERA5-based land/ocean/sea-ice fractions plus CM4's lake fraction do not sum to one
# over lakes; a caveat for that arm only.
ace2p5: dict[str, Any] = copy.deepcopy(cfg)
ace2p5["forcing_loader"]["dataset"] = {
    "merge": [
        cfg["forcing_loader"]["dataset"],
        {
            "data_path": "/ace2p5forcing",
            "file_pattern": "ace2p5_ssp245_forcing.zarr",
            "engine": "zarr",
        },
    ]
}
ace2p5["allow_incompatible_dataset"] = True
h = f"# Atmosphere-only SSP2-4.5 run with prescribed SST, 2015-01-20 .. 2099-12-31 ({N_STEPS} 6-hourly steps): the CM4-line ACE2.5 rs1\n# atmosphere (never coupled fine-tuned), with carbon_dioxide (ppmv) + CM4 lake_fraction from an extra store at /ace2p5forcing.\n# Generated by make_ssp245_atmos_configs.py; launch with EXTRA_DS=<extra store ds> launch-1deg-era5-ssp245-atmos-only.sh.\n"
(HERE / "ssp/ace-ssp245-ace2p5-original.yaml").write_text(
    h + yaml.safe_dump(ace2p5, sort_keys=False, width=120)
)
print("wrote ace2p5-original")

for tag, desc in ARMS.items():
    h = f"# Atmosphere-only SSP2-4.5 run with prescribed SST, 2015-01-20 .. 2099-12-31 ({N_STEPS} 6-hourly steps): {desc}.\n# Generated by make_ssp245_atmos_configs.py; launch with launch-1deg-era5-ssp245-atmos-only.sh.\n"
    (HERE / f"ssp/ace-ssp245-{tag}.yaml").write_text(
        h + yaml.safe_dump(cfg, sort_keys=False, width=120)
    )
    print("wrote", tag, N_STEPS, "steps")
