#!/usr/bin/env python
# ruff: noqa: E501
"""fme.ace.inference configs for a FIXED-SST STEPPED-CO2 sweep of 1deg ERA5 atmospheres (Troy 2026-11-13 "lets try that").

Why: under SSP2-4.5 the 6-hourly ACE2S paper checkpoint's 2 m temperature turns over past ~460 ppm (top-layer temperature flips
to warming, reflected SW +23 W/m2) while ACE2-ERA5 warms monotonically. This sweep maps each checkpoint's learned response as a
function of CO2 alone: the same 10-year prescribed-SST run (2015-01-20 .. 2025-01-20 of the SSP2-4.5 forcing store, whose SST is
ERA5 climatology + a small CM4 anomaly) repeated with global_mean_co2 overwritten by a constant (XarrayDataConfig.overwrite).
Levels: 400 (in-range control), 450, 475, 500, 550, 600 ppm. Monthly means written; wandb global means are the diagnostic.

    python make_co2sweep_configs.py   -> ssp/ace-co2sweep-<ppm>ppm.yaml (checkpoint-agnostic; the launcher picks the checkpoint)
"""

import pathlib
from typing import Any

import yaml

HERE = pathlib.Path(__file__).resolve().parent
START = "2015-01-20T18:00:00"
IN_MEMORY = 40
N_STEPS = 14600  # 10 years of 6-hourly steps
LEVELS_PPM = [400, 450, 475, 500, 550, 600]
cfg: dict[str, Any] = {
    "experiment_dir": "/results",
    "n_forward_steps": N_STEPS,
    "forward_steps_in_memory": IN_MEMORY,
    "checkpoint_path": "/ckpt.tar",
    "logging": {
        "log_to_screen": True,
        "log_to_wandb": True,
        "log_to_file": True,
        "project": "ace-samudra-coupled-cm4",
        "entity": "ai2cm",
    },
    "initial_condition": {
        "path": "/climate-default/2026-03-19-era5-1deg-8layer-1940-2025.zarr",
        "engine": "zarr",
        "start_indices": {"times": [START]},
    },
    "forcing_loader": {
        "num_data_workers": 2,
        "dataset": {
            "data_path": "/climate-default",
            "file_pattern": "2026-04-07-cm4-ssp245-ACE-forcing-dataset.zarr",
            "engine": "zarr",
            "overwrite": {"constant": {"global_mean_co2": None}},
        },
    },
    "data_writer": {
        "save_prediction_files": False,
        "save_monthly_files": True,
        "names": [
            "surface_temperature",
            "TMP2m",
            "PRESsfc",
            "PRATEsfc",
            "DSWRFsfc",
            "DLWRFsfc",
            "ULWRFsfc",
            "USWRFsfc",
            "LHTFLsfc",
            "SHTFLsfc",
            "DSWRFtoa",
            "ULWRFtoa",
            "USWRFtoa",
            "sea_ice_fraction",
            "ocean_fraction",
            "h500",
            "TMP850",
            "air_temperature_7",
            "air_temperature_0",
        ],
    },
    "aggregator": {"log_global_mean_time_series": True},
}
for ppm in LEVELS_PPM:
    cfg["forcing_loader"]["dataset"]["overwrite"]["constant"]["global_mean_co2"] = (
        ppm * 1e-6
    )
    h = f"# Fixed-SST stepped-CO2 sweep member: 10-yr prescribed-SST run (SSP2-4.5 forcing store 2015-01-20..2025-01-20) with global_mean_co2 = {ppm} ppm.\n# Generated by make_co2sweep_configs.py; launch with launch-1deg-era5-co2sweep.sh.\n"
    (HERE / f"ssp/ace-co2sweep-{ppm}ppm.yaml").write_text(
        h + yaml.safe_dump(cfg, sort_keys=False, width=120)
    )
    print("wrote", ppm)
