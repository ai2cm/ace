#!/usr/bin/env python
# ruff: noqa: E501
"""Coupled evaluator configs for the 1deg UFS + ERA5 coupled fine-tunes (single coupled checkpoint, which carries the
rename/scale/fraction config): the full-record free rollout 1994-01-05 .. 2023-10 (2174 coupled steps, monthly outputs, the
30-yr trend/climate protocol) and the 2002-2011 coupled ENSO hindcasts (the 120 monthly ICs of the 4deg protocol, 128 coupled
steps ~ 21 months, atmosphere interactive), split into one job per start year (12 ICs) so a 1deg job fits one GPU.

    python make_eval_configs.py
"""

import copy
import pathlib

import yaml

HERE = pathlib.Path(__file__).resolve().parent
UFS = {
    "data_path": "/climate-default",
    "file_pattern": "2026-10-06-ufs-replay-ocean-1deg-19level-1994-2023.zarr",
    "engine": "zarr",
}
FRAC = {
    "data_path": "/era5frac",
    "file_pattern": "2026-11-05-era5-1deg-6h-ufs-coupled-fractions-1994-2023.zarr",
    "engine": "zarr",
}
ERA5 = {
    "data_path": "/climate-default",
    "file_pattern": "2026-03-19-era5-1deg-8layer-1940-2025.zarr",
    "engine": "zarr",
}
DATASET = {"ocean": UFS, "atmosphere": {"merge": [FRAC, ERA5]}}
LOGGING = {
    "log_to_screen": True,
    "log_to_wandb": True,
    "log_to_file": True,
    "project": "ace-samudra-coupled-cm4",
    "entity": "ai2cm",
}
AGG = {"log_zonal_mean_images": False, "log_histograms": False}

# the UFS 1deg clean store (no CM4 placeholders) is enough for evaluation? No: the ocean checkpoint reads hfgeou/sfdsi/UI/VI,
# so the evaluator needs the cm4vars twin on weka.
UFS["file_pattern"] = "2026-10-06-ufs-replay-ocean-1deg-19level-1994-2023-cm4vars.zarr"

full = {
    "experiment_dir": "/results",
    "checkpoint_path": "/ckpt.tar",
    "n_coupled_steps": 2170,  # 1994-01-05T18 .. 2023-09-20T18, the whole replay record incl. the untouched 2002-2011 decade (2174 stamps; a multiple of coupled_steps_in_memory)
    "coupled_steps_in_memory": 10,
    "loader": {
        "num_data_workers": 2,
        "dataset": DATASET,
        "start_indices": {"times": ["1994-01-05T18:00:00"]},
    },
    "aggregator": AGG,
    "data_writer": {
        "ocean": {
            "save_prediction_files": False,
            "save_monthly_files": True,
            "names": [
                "sst",
                "thetao_0",
                "thetao_5",
                "thetao_10",
                "ocean_sea_ice_fraction",
                "sea_ice_volume",
                "hfds_total_area",
                "zos",
            ],
        },
        "atmosphere": {
            "save_prediction_files": False,
            "save_monthly_files": True,
            "names": [
                "surface_temperature",
                "TMP2m",
                "DSWRFsfc",
                "DLWRFsfc",
                "ULWRFsfc",
                "USWRFsfc",
                "LHTFLsfc",
                "SHTFLsfc",
                "PRATEsfc",
                "eastward_surface_stress",
                "northward_surface_stress",
                "sea_ice_fraction",
                "ocean_fraction",
            ],
        },
    },
    "logging": LOGGING,
}
hdr = "# Full-record coupled free rollout (1994-01-05 .. 2023-09, 2170 coupled steps) of a 1deg UFS + ERA5 coupled fine-tune checkpoint,\n# monthly outputs for the 30-yr trend and climate scoring (the 4deg protocol at 1deg). Generated by make_eval_configs.py.\n"
(
    HERE / "eval/coupled-evaluator-config-ufs1deg-era5-fullrecord-1994-singleckpt.yaml"
).write_text(hdr + yaml.safe_dump(full, sort_keys=False, width=120))

# Full-record rollouts with a constant unaccounted heating in the corrector-kept ocean's heat-content budget, inference only
# (Troy 2026-11-10: "tune the unaccounted heating ... start with the known unaccounted heating"). The override restates the
# corrector-kept fine-tune's corrector (options not restated fall back to defaults) and changes only the constant, an
# ocean-area-mean W/m2 added to the prescribed surface flux the column is scaled to book. Values: the replay's own budget
# residual against the rebuilt atmosphere flux (dOHC/dt - rebuild, the "known" value), the inline-rollout-derived value and
# the residual against MOM6's hfds (see the README of the cooling diagnosis).
UH_VALUES = [
    -0.96,
    -1.7,
    -4.1,
]  # 1deg store budget 1994-2023 (scratchpad ufs_budget_1deg): dOHC/dt +1.43, rebuilt flux +2.39 -> -0.96; MOM6 hfds +5.58 -> -4.15
corr = yaml.safe_load((HERE / "coupled/ufs1deg-ohc-ace2s6h-fto.yaml").read_text())[
    "stepper"
]["ocean"]["stepper"]["step"]["config"]["corrector"]
assert corr["config"]["ocean_heat_content_correction"] == {
    "method": "scaled_temperature"
}
for uh in UH_VALUES:
    c = copy.deepcopy(corr)
    c["config"]["ocean_heat_content_correction"]["constant_unaccounted_heating"] = uh
    cfg = copy.deepcopy(full)
    cfg["ocean_stepper_override"] = {"corrector": c}
    tag = ("m" if uh < 0 else "p") + f"{abs(uh):.2f}".rstrip("0").rstrip(".").replace(
        ".", "p"
    )
    h = hdr.replace(
        "Generated by make_eval_configs.py.",
        f"The ocean corrector is overridden at inference with\n# constant_unaccounted_heating {uh:+.2f} W/m2 (ocean-area mean) in the scaled-temperature heat-content budget; needs a\n# corrector-kept checkpoint. Generated by make_eval_configs.py.",
    )
    (
        HERE
        / f"eval/coupled-evaluator-config-ufs1deg-era5-fullrecord-1994-singleckpt-uh{tag}.yaml"
    ).write_text(h + yaml.safe_dump(cfg, sort_keys=False, width=120))
    print("wrote uh", tag)

# Corrector-OFF full-record rollout: the corrector-kept checkpoint run with the ocean heat-content correction removed at inference
# (Troy 2026-11-12: "lets see what happens with the correctors off for forecasting"). The override restates the corrector-kept
# corrector without its ocean_heat_content_correction entry (default None = no correction); everything else is unchanged. Separates
# what the corrector-kept weights learned from what the inference-time column rescaling does to the trend and the ENSO hindcasts.
nocorr = copy.deepcopy(corr)
del nocorr["config"]["ocean_heat_content_correction"]
cfg = copy.deepcopy(full)
cfg["ocean_stepper_override"] = {"corrector": nocorr}
h = hdr.replace(
    "Generated by make_eval_configs.py.",
    "The ocean corrector is overridden at inference WITHOUT the\n# ocean heat-content correction (corrector off; the other corrections restated); meant for a corrector-kept checkpoint.\n# Generated by make_eval_configs.py.",
)
(
    HERE
    / "eval/coupled-evaluator-config-ufs1deg-era5-fullrecord-1994-singleckpt-nocorr.yaml"
).write_text(h + yaml.safe_dump(cfg, sort_keys=False, width=120))
print("wrote nocorr fullrecord")

# Zero-shot full-record rollout in the two-checkpoint form (ocean-only fine-tune + the original atmosphere, no coupled training):
# the "did FTO create the cooling?" control of the coupled cooling deep dive (Troy 2026-11-10). The stepper options the coupled
# fine-tune configs carry (sst name, fraction prediction, stress rename + sign) must be restated here.
zs = copy.deepcopy(full)
zs["checkpoint_path"] = {
    "ocean": {"timedelta": "5D", "path": "/ocean_ckpt.tar"},
    "atmosphere": {"timedelta": "6h", "path": "/atmos_ckpt.tar"},
    "sst_name": "sst",
    "ocean_fraction_prediction": {
        "land_fraction_name": "land_fraction",
        "sea_ice_fraction_name": "ocean_sea_ice_fraction",
        "sea_ice_fraction_name_in_atmosphere": "sea_ice_fraction",
    },
    "atmosphere_output_rename": {
        "eastward_surface_wind_stress": "eastward_surface_stress",
        "northward_surface_wind_stress": "northward_surface_stress",
    },
    "atmosphere_output_scale": {
        "eastward_surface_wind_stress": -1.0,
        "northward_surface_wind_stress": -1.0,
    },
}
hz = hdr.replace(
    "of a 1deg UFS + ERA5 coupled fine-tune checkpoint,",
    "of a 1deg UFS ocean + ERA5 ACE2S pair in the TWO-CHECKPOINT (zero-shot, no coupled training) form,",
).replace(
    "Generated by make_eval_configs.py.",
    "Launch: launch-1deg-ufs-era5-coupled-zeroshot-eval.sh. Generated by make_eval_configs.py.",
)
(
    HERE / "eval/coupled-evaluator-config-ufs1deg-era5-fullrecord-1994-twockpt.yaml"
).write_text(hz + yaml.safe_dump(zs, sort_keys=False, width=120))

ics = yaml.safe_load(open(HERE / "eval/hindcast_ics_2002_2011.yaml"))
assert len(ics) == 120
for y in range(2002, 2012):
    year_ics = [t for t in ics if t.startswith(str(y))]
    assert len(year_ics) == 12
    hc = {
        "experiment_dir": "/results",
        "checkpoint_path": "/ckpt.tar",
        "n_coupled_steps": 128,
        "coupled_steps_in_memory": 2,  # 12 ICs x 8 steps of 1deg 6-hourly atmosphere OOMs an 80 GB GPU (2026-11-08); 2 fits
        "loader": {
            "num_data_workers": 2,
            "dataset": DATASET,
            "start_indices": {"times": year_ics},
        },
        "aggregator": AGG,
        "data_writer": {
            "ocean": {"save_prediction_files": True, "names": ["sst"]},
            "atmosphere": {"save_prediction_files": False, "save_monthly_files": False},
        },
        "logging": LOGGING,
    }
    h = f"# Coupled ENSO hindcasts of a 1deg UFS + ERA5 coupled fine-tune checkpoint: the 12 monthly {y} starts of the 120-IC 2002-2011\n# protocol (first UFS 5-day stamp of each month) x 128 coupled steps (~21 months), atmosphere interactive; sst prediction files\n# for the Nino3.4 ACC scorer. Generated by make_eval_configs.py.\n"
    (
        HERE
        / f"eval/coupled-evaluator-config-ufs1deg-era5-hindcast-{y}-singleckpt.yaml"
    ).write_text(h + yaml.safe_dump(hc, sort_keys=False, width=120))
    hcn = copy.deepcopy(hc)
    hcn["ocean_stepper_override"] = {"corrector": nocorr}
    hn = h.replace(
        "Generated by make_eval_configs.py.",
        "The ocean corrector is overridden at inference WITHOUT the ocean heat-content\n# correction (corrector off; other corrections restated); meant for a corrector-kept checkpoint. Generated by make_eval_configs.py.",
    )
    (
        HERE
        / f"eval/coupled-evaluator-config-ufs1deg-era5-hindcast-{y}-singleckpt-nocorr.yaml"
    ).write_text(hn + yaml.safe_dump(hcn, sort_keys=False, width=120))
print("wrote eval configs")
