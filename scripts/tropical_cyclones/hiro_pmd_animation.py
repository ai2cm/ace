def parse_cftime(s):
    m = re.match(r"(\d+)-(\d+)-(\d+)[ T](\d+):(\d+):(\d+)", s)
    return cftime.DatetimeJulian(*(int(g) for g in m.groups()))


def load_prmsl(path, ens):
    da = xr.open_zarr(path)["PRMSL"]
    if ens is not None and "ensemble" in da.dims:
        da = da.isel(ensemble=ens)
    return da


def to_mb(v):
    v = np.asarray(v, dtype="float64")
    return v / 100.0 if (v.size and np.nanmean(v) > 2000) else v


def animate(tid, label, positions, fields):
    names = list(MODELS)
    frames = []
    for i, (t_str, la, lo) in enumerate(positions):
        t = parse_cftime(t_str)
        panels, mn, mx = {}, [], []
        for n in names:
            sub = fields[n].sel(time=t, method="nearest").sel(
                latitude=slice(la - WINDOW_DEG, la + WINDOW_DEG),
                longitude=slice(lo - WINDOW_DEG, lo + WINDOW_DEG))
            v = to_mb(sub.values)
            panels[n] = (v, sub["latitude"].values, sub["longitude"].values)
            if np.isfinite(v).any():
                mn.append(np.nanmin(v)); mx.append(np.nanmax(v))
        vmin, vmax = min(mn), max(mx)
        fig, axes = plt.subplots(1, 3, figsize=(11, 4.1))
        for ax, n in zip(axes, names):
            v, lat, lon = panels[n]
            ax.pcolormesh(lon, lat, v, cmap="turbo_r", vmin=vmin, vmax=vmax, shading="auto")
            ax.scatter([lo], [la], marker="x", color="red", s=40)
            ax.set_title(n, fontsize=10)
            ax.set_xticks([]); ax.set_yticks([])
        fig.suptitle(f"Track {tid} ({label}) — {t_str}  [{vmin:.0f}-{vmax:.0f} mb]  "
                     f"frame {i+1}/{len(positions)}", fontsize=10)
        fig.tight_layout(rect=[0, 0, 1, 0.92])
        fig.canvas.draw()
        frames.append(Image.fromarray(np.asarray(fig.canvas.buffer_rgba())).convert("RGB"))
        plt.close(fig)
        if (i + 1) % 15 == 0 or i == len(positions) - 1:
            print(f"  track {tid} frame {i+1}/{len(positions)}", flush=True)
    out = f"/results/hiro_pmd_animation_track{tid}.gif"
    frames[0].save(out, save_all=True, append_images=frames[1:],
                   duration=int(1000 / FPS), loop=0)
    print(f"saved {out}", flush=True)


if __name__ == "__main__":
    fields = {n: load_prmsl(p, e) for n, (p, e) in MODELS.items()}
    for tid, (label, pts) in TRACKS.items():
        animate(tid, label, pts, fields)
    print("DONE", flush=True)
